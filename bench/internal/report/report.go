// Package report turns results into text people read: the full table of what
// was measured, and the comparison of two runs.
package report

import (
	"fmt"
	"math"
	"sort"
	"strings"

	"github.com/Sumit6258/Faultline/bench/internal/model"
	"github.com/Sumit6258/Faultline/bench/internal/stats"
)

// NoisyThreshold is the spread (slowest minus fastest, over the median) above
// which a benchmark's runs disagree too much for its median to be trusted to
// better than a few tens of percent.
const NoisyThreshold = 0.15

// FormatTime writes a duration given in nanoseconds with three significant digits and a sensible unit.
func FormatTime(ns float64) string {
	unit, div := "ns", 1.0
	switch a := math.Abs(ns); {
	case a >= 1e9:
		unit, div = "s", 1e9
	case a >= 1e6:
		unit, div = "ms", 1e6
	case a >= 1e3:
		unit, div = "us", 1e3
	}
	v := ns / div
	switch a := math.Abs(v); {
	case a >= 100:
		return fmt.Sprintf("%.0f %s", v, unit)
	case a >= 10:
		return fmt.Sprintf("%.1f %s", v, unit)
	default:
		return fmt.Sprintf("%.2f %s", v, unit)
	}
}

// DisplayName drops the "Benchmark" prefix, and the package when it is the module's own.
func DisplayName(s model.Series) string {
	name := strings.TrimPrefix(s.Name, "Benchmark")
	if i := strings.Index(s.Package, s.Module); i >= 0 {
		if rel := strings.Trim(s.Package[i+len(s.Module):], "/"); rel != "" {
			return rel + ": " + name
		}
	}
	return name
}

func summary(s model.Series, metric string) (stats.Summary, bool) {
	xs, ok := s.Samples[metric]
	if !ok || len(xs) == 0 {
		return stats.Summary{}, false
	}
	return stats.Summarize(xs), true
}

func intStr(v float64) string { return fmt.Sprintf("%.0f", v) }

// Markdown is the full report for one set of results.
func Markdown(f model.File) string {
	var b strings.Builder
	b.WriteString("# Benchmarks\n\n")
	b.WriteString("Generated by `faultbench report`. Do not edit by hand, regenerate it.\n\n")

	e := f.Env
	commit := e.Commit
	if commit == "" {
		commit = "unknown"
	} else if e.Dirty {
		commit += " (with uncommitted changes)"
	}
	b.WriteString("## Environment\n\n| | |\n|---|---|\n")
	fmt.Fprintf(&b, "| CPU | %s, %d logical CPU(s) |\n", e.CPU, e.NumCPU)
	fmt.Fprintf(&b, "| Platform | %s/%s |\n", e.GOOS, e.GOARCH)
	fmt.Fprintf(&b, "| Go | %s |\n", e.GoVersion)
	if e.PythonVersion != "" {
		fmt.Fprintf(&b, "| Python | %s |\n", e.PythonVersion)
	}
	fmt.Fprintf(&b, "| Commit | %s |\n", commit)
	fmt.Fprintf(&b, "| Date | %s |\n", strings.SplitN(e.Date, "T", 2)[0])
	benchtime := e.BenchTime
	if benchtime == "" {
		benchtime = "the Go default"
	}
	fmt.Fprintf(&b, "| Runs | %d of each benchmark, %s each |\n\n", e.Count, benchtime)

	b.WriteString("**These are numbers from one machine.** Times are properties of a program on a particular computer, ")
	b.WriteString("so they say how things compare to each other here, and nothing about how fast anything is elsewhere. ")
	b.WriteString("Do not compare them with a table made on different hardware.\n\n")
	b.WriteString("- **Time** is the median of the runs, with the fastest and slowest in brackets. When those two are far apart the median is rough, ")
	fmt.Fprintf(&b, "and a `*` marks a benchmark whose runs differed by more than %.0f%%.\n", NoisyThreshold*100)
	b.WriteString("- **B/op** and **allocs/op** are counted by the Go runtime, not timed. They are the same from run to run, so they are the numbers to trust most.\n\n")

	byModule := map[string][]model.Series{}
	var modules []string
	noisy := 0
	for _, s := range f.Series {
		if _, ok := byModule[s.Module]; !ok {
			modules = append(modules, s.Module)
		}
		byModule[s.Module] = append(byModule[s.Module], s)
		if sm, ok := summary(s, "ns/op"); ok && sm.Spread > NoisyThreshold {
			noisy++
		}
	}
	sort.Strings(modules)
	fmt.Fprintf(&b, "%d benchmarks in %d modules, %d of them noisy on this run.\n\n", len(f.Series), len(modules), noisy)

	for _, m := range modules {
		series := byModule[m]
		sort.SliceStable(series, func(i, j int) bool { return series[i].Key() < series[j].Key() })
		extras := map[string]bool{}
		for _, s := range series {
			for metric := range s.Samples {
				if metric != "ns/op" && metric != "B/op" && metric != "allocs/op" {
					extras[metric] = true
				}
			}
		}
		var extraNames []string
		for name := range extras {
			extraNames = append(extraNames, name)
		}
		sort.Strings(extraNames)

		fmt.Fprintf(&b, "## %s\n\n| Benchmark | Time | B/op | allocs/op | Runs |", m)
		for _, name := range extraNames {
			fmt.Fprintf(&b, " %s |", name)
		}
		b.WriteString("\n|---|---|---|---|---|")
		for range extraNames {
			b.WriteString("---|")
		}
		b.WriteString("\n")
		for _, s := range series {
			t, ok := summary(s, "ns/op")
			if !ok {
				continue
			}
			star := ""
			if t.Spread > NoisyThreshold {
				star = " *"
			}
			timeCell := FormatTime(t.Median)
			if t.N > 1 {
				timeCell += fmt.Sprintf(" (%s to %s)", FormatTime(t.Min), FormatTime(t.Max))
			}
			bytes, allocs := "n/a", "n/a"
			if sm, ok := summary(s, "B/op"); ok {
				bytes = intStr(sm.Median)
			}
			if sm, ok := summary(s, "allocs/op"); ok {
				allocs = intStr(sm.Median)
			}
			fmt.Fprintf(&b, "| %s | %s%s | %s | %s | %d |", DisplayName(s), timeCell, star, bytes, allocs, t.N)
			for _, name := range extraNames {
				if sm, ok := summary(s, name); ok {
					fmt.Fprintf(&b, " %.4g |", sm.Median)
				} else {
					b.WriteString(" |")
				}
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}

	if len(f.Failures) > 0 {
		b.WriteString("## Failures\n\nThese did not produce results, so the tables above are incomplete.\n\n")
		for _, fl := range f.Failures {
			fmt.Fprintf(&b, "- `%s`: %s\n", fl.Module, fl.Message)
		}
		b.WriteString("\n")
	}
	return b.String()
}
